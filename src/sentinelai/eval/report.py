"""Build reports/phase3/report.md from the Phase 3 JSON files.

Only numbers present in those files are printed. A run that has not been
done is shown as missing, never filled in.
"""
from __future__ import annotations

import json
from pathlib import Path


def _f(v, nd=3):
    if v is None:
        return "—"
    return f"{v:.{nd}f}" if isinstance(v, float) else f"{v:,}" if isinstance(v, int) else str(v)


def _ci(c: dict, k: str) -> str:
    x = c.get(k) if c else None
    return "—" if not x else f"{x['point']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"


def _load(out: Path, name: str):
    p = out / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _missing(L, what):
    L += [f"*Not run yet: {what}.*", ""]


def write_report(out: Path) -> Path:
    L = ["# Phase 3 evaluation report", "",
         "Generated by `scripts/evaluate_phase3.py` from the JSON files in this folder. "
         "Every threshold and selection below was made on **validation** data; test and holdout were only scored. "
         "Intervals are 95% bootstrap intervals that resample whole (source, 5-minute) blocks "
         "(Stage 2: whole day|5-minute blocks), because neighbouring flows are near-copies.", ""]

    models = _load(out, "models")
    L += ["## 1. All models on the test split", ""]
    if not models:
        _missing(L, "models.json")
    else:
        m = models["models"]
        L += ["`default` = the Phase 2 operating point (0.5 probability; Stage 2 = most likely class; Stage 3 = Phase 2 threshold). "
              "`val 1% FPR` = threshold set so 1% of benign validation flows are flagged.", "",
              "| Model | Operating point | Precision | Recall [95% CI] | FPR [95% CI] | F1 [95% CI] | Reproduces Phase 2 |",
              "|---|---|---|---|---|---|---|"]
        for k, r in m.items():
            for op, v in r["operating_points"].items():
                t, c = v["test"], v["test_ci"]
                L.append(f"| {k} | {op} | {_f(t['precision'])} | {_ci(c, 'recall')} | {_ci(c, 'fpr')} | {_ci(c, 'f1')} | "
                         f"{_f(r['reproduces_phase2']) if op == 'default' else ''} |")
        L += ["", "### Calibration of attack probabilities (test)", "", "| Model | Brier | ECE |", "|---|---|---|"]
        for k, r in m.items():
            if "test_calibration" in r:
                L.append(f"| {k} | {_f(r['test_calibration']['brier'], 4)} | {_f(r['test_calibration']['ece'], 4)} |")
        L += ["", "### Detection per source (test, default operating point)", "",
              "| Model | Source | Benign n | Benign FPR | Attack n | Attacks detected |", "|---|---|---|---|---|---|"]
        for k, r in m.items():
            for s, v in r["operating_points"]["default"].get("test_per_source", {}).items():
                L.append(f"| {k} | {s} | {_f(v['benign_n'])} | {_f(v['benign_fpr'])} | {_f(v['attack_n'])} | {_f(v['attack_detected'])} |")
        L += ["", "### Weakest attack classes (test, default operating point, temporal split)", "",
              "Five lowest detection rates per model. Full tables are in `models.json`; bar charts in `figures/per_class_*.png`.", "",
              "| Model | Class (source) | n | Detected |", "|---|---|---|---|"]
        for k, r in m.items():
            if "stratified" in k:
                continue
            pc = {c: v for c, v in r["operating_points"]["default"]["test_per_class"].items() if c != "Benign"}
            for c, v in sorted(pc.items(), key=lambda kv: kv[1]["flagged"])[:5]:
                L.append(f"| {k} | {c} ({v['source']}) | {_f(v['n'])} | {_f(v['flagged'])} |")
        L += ["", "### Held-out attack classes (never in training)", "",
              "| Model | Operating point | Class | n | Detected | Most common tactic given |", "|---|---|---|---|---|---|"]
        for k, r in m.items():
            for op, v in r["operating_points"].items():
                for c, h in v.get("holdout", {}).items():
                    tc = h.get("tactic_counts", {})
                    top = max(tc, key=tc.get) if tc else "—"
                    L.append(f"| {k} | {op} | {c} | {_f(h['n'])} | {_f(h['detected'])} | {top} |")
        L.append("")

    comb = _load(out, "combined")
    L += ["## 2. Combined detector: Stage 1 alone vs Stage 1 OR Stage 3", ""]
    if not comb:
        _missing(L, "combined.json")
    else:
        L += ["Both detectors are held to the same budget: at most 1% of benign **validation** flows flagged. "
              "The thresholds giving the best validation recall inside that budget were chosen, then scored on test.", "",
              "| Features | Detector | Chosen (S1 FPR, S3 FPR) on val | Val recall | Test recall [CI] | Test FPR [CI] | Backdoor | SSH-Bruteforce | Slowloris |",
              "|---|---|---|---|---|---|---|---|---|"]
        for f, r in comb["combined"].items():
            for name in ("stage1_alone", "stage1_or_stage3"):
                v = r.get(name)
                if not v:
                    L.append(f"| {f} | {name} | no pair inside budget | | | | | | |")
                    continue
                g, h = v["chosen_on_val"], v.get("holdout", {})
                L.append(f"| {f} | {name} | ({g['s1_fpr']}, {g['s3_fpr']}) | {_f(g['val_recall'])} | {_ci(v['test_ci'], 'recall')} | "
                         f"{_ci(v['test_ci'], 'fpr')} | {_f(h.get('Backdoor', {}).get('detected'))} | "
                         f"{_f(h.get('SSH-Bruteforce', {}).get('detected'))} | {_f(h.get('DoS_attacks-Slowloris', {}).get('detected'))} |")
        L.append("")

    loso = _load(out, "loso")
    L += ["## 3. Option A: leave-one-source-out (Stage 1 XGBoost)", ""]
    if not loso:
        _missing(L, "loso.json")
    else:
        L += ["Trained on three source datasets, tested on **every** flow of the fourth. "
              "`seen` = the Phase 2 temporal model, which trained on that source, on its test rows of the same source.", "",
              "| Features | Unseen source | Test rows | F1 [CI] | FPR [CI] | ROC-AUC | F1 at val 1% FPR | FPR at val 1% FPR | Seen-source F1 | Seen-source FPR | Tactics never trained on | Tactic right (known tactics) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        key = f"val_fpr_{loso['loso']['target_fpr']:g}"
        for r in loso["loso"]["runs"]:
            c, v, b = r["default_ci"], r[key], r["in_source_baseline"]
            L.append(f"| {r['feature_set']} | {r['test_source']} | {_f(r['test_rows'])} | {_ci(c, 'f1')} | {_ci(c, 'fpr')} | "
                     f"{_f(r['roc_auc'])} | {_f(v['f1'])} | {_f(v['fpr'])} | {_f(b['f1'])} | {_f(b['fpr'])} | "
                     f"{', '.join(r['tactics_unseen_in_training']) or '—'} | {_f(r['tactic_correct_on_known_attacks'])} |")
        L.append("")

    sv = _load(out, "stage3_variants")
    L += ["## 4. Option B: Stage 3 per-source variants", ""]
    if not sv:
        _missing(L, "stage3_variants.json")
    else:
        for f, r in sv["stage3_variants"].items():
            L += [f"### Features: {f}", "", f"Selection rule ({r['selection_rule']}): **{r['selected_on_val']}**.", "",
                  "| Variant | Val recall | Val FPR | Test recall [CI] | Test FPR [CI] | Backdoor | SSH-Bruteforce | Slowloris |",
                  "|---|---|---|---|---|---|---|---|"]
            for name, v in r["variants"].items():
                h = v["holdout"]
                L.append(f"| {name}{' (selected)' if name == r['selected_on_val'] else ''} | {_f(v['val']['recall'])} | {_f(v['val']['fpr'])} | "
                         f"{_ci(v['test_ci'], 'recall')} | {_ci(v['test_ci'], 'fpr')} | {_f(h.get('Backdoor', {}).get('detected'))} | "
                         f"{_f(h.get('SSH-Bruteforce', {}).get('detected'))} | {_f(h.get('DoS_attacks-Slowloris', {}).get('detected'))} |")
            L += ["", "| Variant | Source | Benign FPR | Attacks detected |", "|---|---|---|---|"]
            for name, v in r["variants"].items():
                for s, x in v["test_per_source"].items():
                    L.append(f"| {name} | {s} | {_f(x['benign_fpr'])} | {_f(x['attack_detected'])} |")
            L += ["", "Per-source autoencoders were trained on:", "",
                  "| Source | Benign train rows | Benign val rows | Epochs |", "|---|---|---|---|"]
            for s, x in r["per_source_models"].items():
                L.append(f"| {s} | {_f(x['benign_train_rows'])} | {_f(x['benign_val_rows'])} | {x['epochs_run']} |")
            L.append("")

    lab = _load(out, "lab")
    L += ["## 5. Real lab flows", ""]
    if not lab:
        _missing(L, "lab.json")
    else:
        lb = lab["lab"]
        L += [f"{lb['rows']} real conversations, **{lb['attacks']} attack**. This shows what the false alarms are; "
              "it is not a precision or recall estimate.", "",
              "| Model | Operating point | Flagged | Attack caught | False alarms | Flagged by protocol (flagged/n) |",
              "|---|---|---|---|---|---|"]
        for k, ops in lb["models"].items():
            for op, v in ops.items():
                proto = ", ".join(f"{p['PROTOCOL']}: {p['flagged']}/{p['n']}" for p in v["flagged_by_protocol"])
                L.append(f"| {k} | {op} | {v['tp'] + v['fp']} | {v['attack_flagged']} | {v['fp']} | {proto} |")
        L += ["", "Protocol numbers: 1 = ICMP, 2 = IGMP, 6 = TCP, 17 = UDP.", ""]

    L += ["## Figures", "", "All in `figures/`: `confusion_*` (tactic confusion matrices), `per_class_*` (detection per attack class), "
          "`roc_pr_*`, `calibration.png`, `ae_scores_*` (autoencoder score distributions per source), `loso_*`, `stage3_variants_*`.", ""]
    path = out / "report.md"
    out.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8")
    return path
