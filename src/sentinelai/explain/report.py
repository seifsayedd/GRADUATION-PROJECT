"""Figures and report.md for Phase 4, built only from the JSON files in reports/phase4/."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

BLUE, RED, GREY = "#2563eb", "#dc2626", "#9ca3af"


def _load(out: Path, name: str):
    p = out / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _f(v, nd=3):
    if v is None:
        return "—"
    return f"{v:.{nd}f}" if isinstance(v, float) else f"{v:,}" if isinstance(v, int) else str(v)


def _save(fig, p: Path):
    p.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(p, dpi=110)
    plt.close(fig)


def _hbar(d: dict, title: str, xlabel: str, p: Path, signed: bool = False):
    items = list(d.items())[::-1]
    fig, ax = plt.subplots(figsize=(6.5, 0.32 * len(items) + 1.3))
    ax.barh([k for k, _ in items], [v for _, v in items],
            color=[(RED if v > 0 else BLUE) if signed else BLUE for _, v in items])
    if signed:
        ax.axvline(0, c=GREY, lw=1)
    ax.set_xlabel(xlabel), ax.set_title(title, fontsize=10), ax.tick_params(axis="y", labelsize=8)
    _save(fig, p)


def write_figures(out: Path) -> Path:
    figs = out / "figures"
    s1 = _load(out, "stage1")
    if s1:
        for name, r in s1["stage1"].items():
            if not name.startswith("xgboost"):
                continue
            _hbar(r["importance_by_true_tactic"]["overall"], f"{name}: mean |SHAP| (flagged test flows)",
                  "mean |SHAP| (log-odds)", figs / f"importance_{name}.png")
            byg = r["importance_by_true_tactic"]["by_group"]
            feats = list(r["importance_by_true_tactic"]["overall"])[:12]
            tactics = sorted(byg)
            M = np.array([[byg[t].get(f, np.nan) for f in feats] for t in tactics], dtype=float)
            fig, ax = plt.subplots(figsize=(1.0 + 0.6 * len(feats), 0.9 + 0.5 * len(tactics)))
            ax.imshow(np.nan_to_num(M), cmap="Blues", aspect="auto")
            ax.set_xticks(range(len(feats)), feats, rotation=50, ha="right", fontsize=7)
            ax.set_yticks(range(len(tactics)), tactics, fontsize=8)
            ax.set_title(f"{name}: mean |SHAP| by true tactic (blank = not in that tactic's top 15)", fontsize=9)
            _save(fig, figs / f"importance_by_tactic_{name}.png")
            if r.get("false_alarm_drivers"):
                _hbar(r["false_alarm_drivers"], f"{name}: what pushes benign test flows to an alert",
                      "mean SHAP (log-odds); red = towards attack", figs / f"false_alarms_{name}.png", signed=True)
    lab = _load(out, "lab")
    if lab:
        for name, r in lab["lab"].items():
            if isinstance(r, dict) and r.get("false_alarm_drivers"):
                _hbar(r["false_alarm_drivers"], f"Lab false alarms, {name}", "mean SHAP; red = towards attack",
                      figs / f"lab_false_alarms_{name}.png", signed=True)
    s2 = _load(out, "stage2")
    if s2:
        fig, ax = plt.subplots(figsize=(7, 3.4))
        for name, r in s2["stage2"].items():
            d = r["mean_attention_by_offset"]
            ax.plot([int(k) for k in d], list(d.values()), marker=".", label=name)
        ax.set_xlabel("position in window (0 = the labelled flow)"), ax.set_ylabel("mean attention weight")
        ax.set_title("Stage 2: where attention goes (flagged test flows)", fontsize=10), ax.legend(fontsize=8)
        _save(fig, figs / "stage2_attention_by_offset.png")
    return figs


def write_report(out: Path) -> Path:
    L = ["# Phase 4 explainability report", "",
         "Generated by `scripts/explain_phase4.py` from the JSON files in this folder. Explanations come from the models "
         "themselves (TreeSHAP, attention weights, reconstruction error). Example explanation objects are in `examples/` "
         "and `lab/`; their format is `docs/schema/explanation.schema.json`.", ""]
    s1 = _load(out, "stage1")
    L += ["## 1. Stage 1 (SHAP)", ""]
    if not s1:
        L += ["*Not run yet.*", ""]
    else:
        L += ["### Additivity (base value + contributions = model output)", "",
              "| Model | Rows | Max error, attack model | Max error, tactic model | Space |", "|---|---|---|---|---|"]
        for n, r in s1["stage1"].items():
            a = r["additivity"]
            L.append(f"| {n} | {_f(r['rows'])} | {a['binary']:.1e} | {a['tactic']:.1e} | {a['space']['binary']} / {a['space']['tactic']} |")
        L += ["", "### Most important features (mean |SHAP|, flagged test flows)", "", "| Model | Top 8 features |", "|---|---|"]
        for n, r in s1["stage1"].items():
            L.append(f"| {n} | {', '.join(list(r['importance_by_true_tactic']['overall'])[:8])} |")
        L += ["", "### Top 5 features per true tactic (XGBoost, all features)", "", "| True tactic | Top 5 features |", "|---|---|"]
        x = s1["stage1"].get("xgboost_temporal_full")
        if x:
            for t, d in sorted(x["importance_by_true_tactic"]["by_group"].items()):
                L.append(f"| {t} | {', '.join(list(d)[:5])} |")
        L += ["", "### What pushes benign test flows into an alert (mean SHAP over flagged benign flows)", "",
              "| Model | Feature: mean SHAP |", "|---|---|"]
        for n, r in s1["stage1"].items():
            L.append(f"| {n} | {'; '.join(f'{k}: {v:+.3f}' for k, v in list(r['false_alarm_drivers'].items())[:6])} |")
        L += ["", "### Deletion test", "",
              "Each flagged flow's top-k features (by SHAP towards attack) are set to typical benign values; "
              "compared with setting k random features. Larger drop = the explanation points at what the model uses.", "",
              "| Model | k | Mean drop, top-k | Mean drop, random k | Top-k beats random | Flipped to benign, top-k | Flipped, random |",
              "|---|---|---|---|---|---|---|"]
        for n, r in s1["stage1"].items():
            for k, v in (r.get("deletion") or {}).items():
                if k.startswith("k="):
                    L.append(f"| {n} | {k[2:]} | {_f(v['mean_drop_top'])} | {_f(v['mean_drop_random'])} | {_f(v['share_top_beats_random'])} | "
                             f"{_f(v['share_flipped_to_benign_top'])} | {_f(v['share_flipped_to_benign_random'])} |")
        L += ["", "### Stability (Spearman correlation of SHAP vectors)", "",
              "Many nearest neighbours are near-copies (see distance), so this is a weak test: it shows explanations are "
              "deterministic for near-identical flows, not that they are robust to meaningful changes.", "",
              "| Model | Nearest-neighbour pairs (median) | Random pairs (median) | Median neighbour distance (model space) |", "|---|---|---|---|"]
        for n, r in s1["stage1"].items():
            if "stability" in r:
                s = r["stability"]
                L.append(f"| {n} | {_f(s['median_rho_nearest_neighbour'])} | {_f(s['median_rho_random_pair'])} | {s['median_neighbour_distance']:.4f} |")
        L.append("")
    ho = _load(out, "holdout")
    L += ["## 2. Attacks never seen in training", ""]
    if not ho:
        L += ["*Not run yet.*", ""]
    else:
        L += ["| Model | Class | Detected | Tactic given (flagged) | Strongest mean SHAP on missed flows |", "|---|---|---|---|---|"]
        for n, r in ho["holdout"].items():
            for cls, v in r.items():
                miss = v.get("binary_mean_shap_missed") or {}
                L.append(f"| {n} | {cls} | {_f(v['detected'])} | {', '.join(f'{k}: {c}' for k, c in v['tactic_given'].items()) or '—'} | "
                         f"{'; '.join(f'{k} {s:+.2f}' for k, s in list(miss.items())[:4]) or '—'} |")
        L.append("")
    lab = _load(out, "lab")
    L += ["## 3. Real lab flows: why the false alarms happen", ""]
    if not lab:
        L += ["*Not run yet.*", ""]
    else:
        lb = lab["lab"]
        L += [f"{lb['rows']} real conversations, {lb['attacks']} attack. All per-conversation explanations: `lab/*.json`.", ""]
        for n in ("xgboost_temporal_lab", "random_forest_temporal_lab"):
            r = lb.get(n)
            if not r:
                continue
            L += [f"### {n}: {r['flagged']} flagged, {r['false_alarms']} false alarms, attack caught: {r['attack_flagged']}", "",
                  "| Feature | Mean SHAP on false alarms | Lab false-alarm median | BigFlow benign median | Lab median's percentile in BigFlow benign |",
                  "|---|---|---|---|---|"]
            for f, v in r["false_alarm_drivers"].items():
                c = r["value_comparison"].get(f, {})
                L.append(f"| {f} | {v:+.3f} | {_f(c.get('lab_false_alarm_median'))} | {_f(c.get('bigflow_benign_median'))} | "
                         f"{_f(c.get('lab_median_percentile_in_bigflow_benign'), 1)} |")
            L += ["", f"Tactic given to the false alarms: {r['tactic_given_to_false_alarms']}", ""]
        ae = lb.get("autoencoder_temporal_lab")
        if ae:
            L += [f"Autoencoder: {ae['flagged']} of {lb['rows']} flagged. Share of reconstruction error by feature: "
                  + ", ".join(f"{k} {v:.0%}" for k, v in ae["mean_error_share_top"].items()) + ".", ""]
    un = _load(out, "units")
    if un:
        L += ["### Do the lab's rate features mean the same as BigFlow's?", "",
              "Checked on BigFlow training flows: the ratio between BigFlow's column and the formula the lab mapping uses "
              "(1.0 = same definition).", "",
              "| Source | SECOND_BYTES = 0 | SECOND_BYTES vs bytes/s (lab formula): median ratio, within 5% | "
              "AVG_THROUGHPUT vs bits/s over whole flow | AVG_THROUGHPUT vs bits/s over forward duration (lab formula) |",
              "|---|---|---|---|---|"]
        for s, v in un["units"].items():
            a, b, c = (v[k] for k in list(v)[2:5])
            L.append(f"| {s} | {v['SRC_TO_DST_SECOND_BYTES_zero_share']:.0%} | {a['median_ratio']:.4g}, {a['share_within_5pct']:.0%} | "
                     f"{b['median_ratio']:.3f}, {b['share_within_5pct']:.0%} | {c['median_ratio']:.3f}, {c['share_within_5pct']:.0%} |")
        L.append("")
    s3 = _load(out, "stage3")
    L += ["## 4. Stage 3 (reconstruction error by feature)", ""]
    if not s3:
        L += ["*Not run yet.*", ""]
    else:
        for n, r in s3["stage3"].items():
            L += [f"### {n}: {r['flagged']} of {r['rows']} sampled test flows flagged; max additivity error {r['max_additivity_error']:.1e}", "",
                  "| True tactic | Features with the largest share of error |", "|---|---|"]
            for t, d in r["error_share_by_true_tactic"].items():
                L.append(f"| {t} | {', '.join(f'{k} {v:.0%}' for k, v in list(d.items())[:4])} |")
            L.append("")
    s2 = _load(out, "stage2")
    L += ["## 5. Stage 2 (attention, checked by removing one flow at a time)", ""]
    if not s2:
        L += ["*Not run yet.*", ""]
    else:
        L += ["| Model | Windows | Top-attended earlier flow is the most influential | Random pick | Expected by chance | "
              "Median Spearman (attention vs influence) | Mean attention on the labelled flow itself |", "|---|---|---|---|---|---|---|"]
        for n, r in s2["stage2"].items():
            a = r["attention_vs_occlusion"]
            L.append(f"| {n} | {_f(a['windows'])} | {_f(a['top_attended_is_most_influential'])} | {_f(a['random_pick_is_most_influential'])} | "
                     f"{_f(a['expected_random_rate'])} | {_f(a['median_spearman_attention_vs_occlusion'])} | {_f(r['mean_attention_on_labelled_flow'])} |")
        L.append("")
    L += ["## Figures", "", "In `figures/`: `importance_*`, `importance_by_tactic_*`, `false_alarms_*`, `lab_false_alarms_*`, "
          "`stage2_attention_by_offset.png`.", ""]
    p = out / "report.md"
    out.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(L), encoding="utf-8")
    return p
